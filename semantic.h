/*
 * semantic.h — семантический анализ: обнаружение повторных объявлений полей.
 *
 * После того как LL(1)-парсер подтвердил синтаксическую корректность входа,
 * семантический проверяльщик делает второй проход по тем же токенам и
 * проверяет единственное семантическое правило задания:
 *
 *   ПРАВИЛО: внутри одной структуры все имена полей должны быть уникальными.
 *            Если одно и то же имя объявлено дважды — сообщаем о ВТОРОМ объявлении.
 *
 * Подход: конечный автомат (КА) над потоком токенов
 * --------------------------------------------------
 * Поскольку синтаксис уже проверен, можно уверенно полагаться на то,
 * что последовательность токенов строго соответствует грамматике.
 * Для решения задачи достаточно небольшого КА:
 *
 *   Состояние      Что означает                    Переход
 *   ─────────────  ─────────────────────────────   ──────────────────────────────
 *   INITIAL        между объявлениями структур     видим 'struct'  → AFTER_STRUCT
 *   AFTER_STRUCT   только что встретили 'struct'   видим identifier→ STRUCT_NAMED
 *   STRUCT_NAMED   знаем имя структуры             видим '{'       → IN_BODY
 *   IN_BODY        внутри тела, начало оператора   видим тип-токен → AFTER_TYPE
 *                                                  видим '}'       → AFTER_CLOSE
 *   AFTER_TYPE     после токена-типа               видим identifier→ FIELD_NAMED
 *   FIELD_NAMED    имя поля записано               видим ';'       → IN_BODY
 *                                                  видим '['       → IN_ARRAY
 *   IN_ARRAY       внутри [N], ждём целое число    видим integer   → ARRAY_INT
 *   ARRAY_INT      видели целое число              видим ']'       → FIELD_NAMED
 *   AFTER_CLOSE    видели закрывающую '}'          видим ';'       → INITIAL
 *
 * "тип-токен" означает: KW_INT | KW_DOUBLE | KW_FLOAT | KW_CHAR |
 *                        KW_BOOL | KW_STRING | IDENTIFIER
 *
 * Таблица имён полей очищается при входе в новое тело структуры.
 * Проверка дублей происходит в переходе AFTER_TYPE → FIELD_NAMED.
 */

#pragma once

#include "lexer.h"

#include <map>
#include <string>
#include <utility>
#include <vector>

// =============================================================================
// SemanticResult — результат одного прохода семантической проверки
// =============================================================================
struct SemanticResult {
    bool        ok;    // true = конфликтов имён не обнаружено
    std::string name;  // конфликтующее имя (когда ok == false)
    int         line;  // позиция ВТОРОГО (повторного) объявления
    int         col;

    static SemanticResult success() {
        return {true, "", 0, 0};
    }
    static SemanticResult conflict(const std::string& n, int l, int c) {
        return {false, n, l, c};
    }
};

// =============================================================================
// SemanticChecker — класс семантического анализатора
// =============================================================================
class SemanticChecker {
public:
    /*
     * check(tokens)
     * -------------
     * Проходит по уже проверенному потоку токенов и ищет повторные объявления
     * имён полей внутри одной структуры.
     *
     * @param tokens  Тот же вектор токенов, что передавался парсеру.
     *                Последний элемент — EOF_TOKEN.
     * @return SemanticResult::success() если конфликтов нет,
     *         SemanticResult::conflict() при первом обнаруженном дубле.
     */
    SemanticResult check(const std::vector<Token>& tokens);

private:
    // Вспомогательный метод: true если токен может быть типом поля
    static bool isTypeToken(const Token& tok);
};
