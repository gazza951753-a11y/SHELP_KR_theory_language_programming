/*
 * codegen.h — генерация промежуточного кода и его оптимизация.
 *
 * После того как парсер построил дерево (AST), нам надо превратить его
 * в «плоский» код — трёхадресный (3AC, Three-Address Code).
 *
 * Трёхадресный код — это набор простых инструкций вида:
 *   t1 = a + 3        (бинарная операция: результат, левый, оператор, правый)
 *   t2 = b + 2
 *   result = t1 * t2  (или копирование:   результат = значение)
 *
 * Мы делаем два варианта кода:
 *
 * 1) Неоптимизированный (rawCode_):
 *    Тупо обходим дерево, каждую операцию пишем как отдельную инструкцию.
 *    На каждую операцию создаём новую временную переменную (t1, t2, t3, ...).
 *    В конце: result = t_последняя  (явное копирование).
 *
 * 2) Оптимизированный (optCode_):
 *    Делаем то же самое, но с двумя улучшениями:
 *
 *    а) Свёртка констант (constant folding):
 *       Если видим операцию где ОБА операнда — числа (например 2 + 5),
 *       то считаем результат прямо сейчас (получаем 7) и не генерируем
 *       инструкцию вообще. Экономим время выполнения программы!
 *
 *    б) Устранение лишнего копирования:
 *       Вместо  result = t4  в конце, просто переименовываем t4 в result
 *       прямо в той инструкции, где он создаётся. Одна инструкция экономится.
 *
 * Ещё собираем таблицу символов — список всех переменных и констант
 * с их типами и позициями в исходном тексте.
 */

#pragma once

#include "ast.h"

#include <map>
#include <ostream>
#include <string>
#include <vector>

// =============================================================================
// Одна запись в таблице символов
// =============================================================================
struct SymbolEntry {
    std::string name;       // имя (переменной или числа)
    std::string kind;       // "variable", "integer" или "float"
    bool        hasValue;   // true если значение известно (т.е. это константа)
    double      value;      // числовое значение (только для констант)
    int         line;       // строка первого появления в тексте
    int         col;        // столбец первого появления в тексте
};

// =============================================================================
// Одна трёхадресная инструкция
// =============================================================================
struct TAC {
    std::string result;  // куда пишем результат (переменная или временная)
    std::string arg1;    // первый операнд
    std::string op;      // операция: "+" или "*". Если пусто — это копирование
    std::string arg2;    // второй операнд (пусто при копировании)
};

// =============================================================================
// Генератор кода
// =============================================================================
class CodeGen {
public:
    // Конструктор — обнуляем счётчик временных переменных и флаг оптимизации
    CodeGen() : tempCount_(0), foldingApplied_(false) {}

    // Главный метод: запускает все проходы (символы + raw-код + opt-код)
    void generate(const ASTNode* root);

    // Вывести таблицу символов в виде красивой таблицы со столбцами
    void printSymbolTable(std::ostream& os) const;

    // Вывести неоптимизированный код (один из разделов output.txt)
    void printRawCode(std::ostream& os) const;

    // Вывести оптимизированный код (один из разделов output.txt)
    void printOptCode(std::ostream& os) const;

    // Возвращает true если хотя бы одна константная свёртка была применена
    bool wasFoldingApplied() const { return foldingApplied_; }

private:
    // --- Таблица символов ---
    std::vector<SymbolEntry>   symbols_;   // все символы в порядке встречи
    std::map<std::string, int> symIndex_;  // быстрый поиск: имя -> индекс в symbols_

    // --- Сгенерированные инструкции ---
    std::vector<TAC> rawCode_;  // неоптимизированный код
    std::vector<TAC> optCode_;  // оптимизированный код

    // --- Служебные переменные ---
    int  tempCount_;       // сколько временных переменных уже создали
    bool foldingApplied_;  // применялась ли свёртка констант хоть раз

    // -------------------------------------------------------------------------
    // Внутренние методы (private, снаружи не нужны)
    // -------------------------------------------------------------------------

    // Первый проход — обходим дерево и собираем все имена и числа в таблицу
    void collectSymbols(const ASTNode* node);

    // Добавить символ в таблицу (если такого имени ещё нет — дубли не пишем)
    void addSymbol(const std::string& name, const std::string& kind,
                   bool hasValue, double value, int line, int col);

    // Определить тип числа по его строке: "integer" или "float"
    // (если в строке есть точка или e/E — это float, иначе integer)
    static std::string numKind(const std::string& raw);

    // Второй проход: генерируем неоптимизированный 3AC, обходя дерево
    std::string genRaw(const ASTNode* node);

    // Третий проход: генерируем оптимизированный 3AC со свёрткой констант
    std::string genOptExpr(const ASTNode* node);  // для выражений (не assign)
    std::string genOpt(const ASTNode* node);       // для корневого узла assign

    // Создать новую временную переменную: t1, t2, t3, ...
    std::string newTemp();

    // Проверить, является ли имя числовой константой с известным значением
    bool   isConstant(const std::string& name) const;
    double getConstValue(const std::string& name) const;

    // Проверить, выглядит ли имя как временная переменная (начинается с t + цифры)
    static bool isTempName(const std::string& name);

    // Превратить double в строку: целые пишем без точки (7 а не 7.000000)
    static std::string formatNumber(double v);
};
