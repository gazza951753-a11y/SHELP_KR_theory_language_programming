/**
 * codegen.h — генерация промежуточного кода и оптимизация.
 *
 * Выполняет два прохода по АСД:
 *
 * 1. Сбор таблицы символов (collectSymbols):
 *    Обходит дерево, регистрирует все идентификаторы и числовые константы
 *    с их типами и позициями в исходном коде.
 *
 * 2a. Генерация неоптимизированного кода (genRaw):
 *    Прямая генерация трёхадресного кода (3AC).
 *    Каждая бинарная операция → отдельная инструкция с новой временной переменной ti.
 *    Присваивание завершается явной инструкцией копирования:  result = t_last
 *
 * 2b. Генерация оптимизированного кода (genOpt):
 *    • Свёртка констант (constant folding):
 *        Если оба операнда бинарной операции — известные числовые константы,
 *        вычисляем результат во время компиляции и используем его напрямую.
 *    • Устранение лишнего копирования:
 *        Последнюю временную переменную переименовываем в целевую (result),
 *        избегая инструкции вида  result = t_last.
 *
 * Формат трёхадресных инструкций (TAC):
 *   result = arg1 op arg2   —  бинарная операция
 *   result = arg1           —  копирование (op == "")
 */

#pragma once

#include "ast.h"

#include <map>
#include <ostream>
#include <string>
#include <vector>

// =============================================================================
// Запись таблицы символов
// =============================================================================
struct SymbolEntry {
    std::string name;       ///< Имя символа (переменной или константы)
    std::string kind;       ///< "variable" | "integer" | "float"
    bool        hasValue;   ///< true, если значение известно на этапе компиляции
    double      value;      ///< Числовое значение (для констант)
    int         line;       ///< Строка первого вхождения
    int         col;        ///< Столбец первого вхождения
};

// =============================================================================
// Трёхадресная инструкция (TAC — Three-Address Code)
// =============================================================================
struct TAC {
    std::string result;  ///< Имя переменной-получателя (левая часть)
    std::string arg1;    ///< Первый операнд
    std::string op;      ///< Оператор: "+" | "*" | "" (копирование)
    std::string arg2;    ///< Второй операнд (пусто при копировании)
};

// =============================================================================
// Генератор кода
// =============================================================================
class CodeGen {
public:
    CodeGen() : tempCount_(0), foldingApplied_(false) {}

    /**
     * Запустить всю генерацию: сбор символов, генерацию сырого и
     * оптимизированного кода.
     */
    void generate(const ASTNode* root);

    /// Вывести таблицу символов в форматированном ASCII-виде
    void printSymbolTable(std::ostream& os) const;

    /// Вывести неоптимизированный трёхадресный код
    void printRawCode(std::ostream& os) const;

    /// Вывести оптимизированный трёхадресный код
    void printOptCode(std::ostream& os) const;

    /// Возвращает true, если в оптимизированном коде применялась свёртка констант
    bool wasFoldingApplied() const { return foldingApplied_; }

private:
    // --- Таблица символов ---
    std::vector<SymbolEntry>   symbols_;   ///< Символы в порядке появления
    std::map<std::string, int> symIndex_;  ///< name → индекс в symbols_

    // --- Инструкции ---
    std::vector<TAC> rawCode_;  ///< Неоптимизированный код
    std::vector<TAC> optCode_;  ///< Оптимизированный код

    // --- Состояние ---
    int  tempCount_;       ///< Счётчик временных переменных (t1, t2, ...)
    bool foldingApplied_;  ///< Была ли применена свёртка констант

    // -------------------------------------------------------------------------
    // Внутренние методы
    // -------------------------------------------------------------------------

    // Фаза сбора символов
    void collectSymbols(const ASTNode* node);
    void addSymbol(const std::string& name, const std::string& kind,
                   bool hasValue, double value, int line, int col);

    // Определить «вид» числовой константы по её исходному тексту:
    //   "integer" — нет '.', 'e', 'E'
    //   "float"   — есть '.' или 'e'/'E'
    static std::string numKind(const std::string& raw);

    // Генерация неоптимизированного кода
    std::string genRaw(const ASTNode* node);

    // Генерация оптимизированного кода
    // node  — текущий узел
    // Возвращает имя, в котором хранится результат (temp, переменная, константа)
    std::string genOptExpr(const ASTNode* node);
    std::string genOpt(const ASTNode* node);

    // Выделить новую временную переменную (t1, t2, ...)
    std::string newTemp();

    // Проверить, является ли имя известной числовой константой
    bool   isConstant(const std::string& name) const;
    double getConstValue(const std::string& name) const;

    // Проверить, является ли имя временной переменной (начинается с 't', далее цифры)
    static bool isTempName(const std::string& name);

    // Форматировать число: без лишних знаков после запятой для целых
    static std::string formatNumber(double v);
};
