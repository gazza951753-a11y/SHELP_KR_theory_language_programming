/*
 * grammar.h — представление грамматики, вычисление FIRST/FOLLOW/направляющих
 *             множеств и построение таблицы LL(1)-разбора.
 *
 * Этот модуль отвечает за всё, что происходит между чтением grammar.txt
 * и передачей готовой таблицы разбора парсеру.
 *
 * Конвейер обработки:
 * ┌──────────────────────────────────────────────────────────────────────┐
 * │  grammar.txt                                                         │
 * │       │  loadFromFile()                                              │
 * │       ▼                                                              │
 * │  Правила + нетерминалы + терминалы                                  │
 * │       │  computeFirstSets()                                          │
 * │       ▼                                                              │
 * │  FIRST(A) для каждого символа A                                     │
 * │       │  computeFollowSets()                                         │
 * │       ▼                                                              │
 * │  FOLLOW(A) для каждого нетерминала A                                │
 * │       │  buildParseTable()                                           │
 * │       ▼                                                              │
 * │  T(A → α) — направляющие множества → таблица[A][терминал] = номер  │
 * │       │  isLL1()                                                     │
 * │       ▼                                                              │
 * │  true / false (нет конфликтов / есть конфликты)                    │
 * └──────────────────────────────────────────────────────────────────────┘
 *
 * Формат файла grammar.txt:
 *  • Одна группа правил на строку: "ЛЧС -> альт1 | альт2 | ..."
 *  • Символы разделены пробелами
 *  • Пустая цепочка (эпсилон) записывается как "eps"
 *  • Специальные терминалы: <identifier>, <integer>
 *  • Первая строка — стартовый нетерминал
 *  • Строки, начинающиеся с '#', считаются комментариями и игнорируются
 */

#pragma once

#include <map>
#include <set>
#include <string>
#include <vector>

// =============================================================================
// Rule — одно правило вывода вида A → X1 X2 … Xn
// =============================================================================
struct Rule {
    std::string              lhs; // левая часть (всегда нетерминал)
    std::vector<std::string> rhs; // правая часть; пустой вектор означает ε
};

// =============================================================================
// Grammar — полное описание грамматики с предвычисленными множествами и таблицей
// =============================================================================
class Grammar {
public:
    /*
     * loadFromFile(filename)
     * ----------------------
     * Загружает грамматику из файла filename.
     * Возвращает true при успехе. При ошибке открытия файла — false.
     * После успешного вызова все множества и таблица разбора готовы к работе.
     */
    bool loadFromFile(const std::string& filename);

    // Возвращает true, если грамматика является LL(1) (нет конфликтов)
    bool isLL1() const { return ll1_; }

    // Все правила вывода в порядке появления в файле
    const std::vector<Rule>& getRules() const { return rules_; }

    // Стартовый нетерминал (ЛЧС первого правила)
    const std::string& getStartSymbol() const { return startSymbol_; }

    // Методы классификации символов
    bool isTerminal(const std::string& sym)    const { return terminals_.count(sym)    != 0; }
    bool isNonterminal(const std::string& sym) const { return nonterminals_.count(sym) != 0; }

    // Таблица LL(1)-разбора: table[нетерминал][терминал] = индекс правила в getRules()
    const std::map<std::string, std::map<std::string, int>>& getParseTable() const {
        return parseTable_;
    }

    // Доступ к FIRST/FOLLOW множествам (удобно для отладки и распечатки)
    const std::map<std::string, std::set<std::string>>& getFirstSets()  const { return firstSets_;  }
    const std::map<std::string, std::set<std::string>>& getFollowSets() const { return followSets_; }

private:
    // -------------------------------------------------------------------------
    // Данные грамматики
    // -------------------------------------------------------------------------
    std::vector<Rule>        rules_;         // все правила вывода
    std::string              startSymbol_;   // стартовый нетерминал
    std::set<std::string>    nonterminals_;  // множество нетерминалов
    std::set<std::string>    terminals_;     // множество терминалов

    // Предвычисленные множества
    std::map<std::string, std::set<std::string>> firstSets_;   // FIRST(A)
    std::map<std::string, std::set<std::string>> followSets_;  // FOLLOW(A)

    // Таблица разбора: [нетерминал][терминал] → индекс правила
    std::map<std::string, std::map<std::string, int>> parseTable_;

    bool ll1_ = false;  // флаг: является ли грамматика LL(1)

    // -------------------------------------------------------------------------
    // Внутренние шаги вычисления
    // -------------------------------------------------------------------------

    /*
     * parseRuleLine(line)
     * -------------------
     * Разбирает одну строку файла грамматики, например:
     *     TYPE -> int | double | float | <identifier>
     * Разбивает альтернативы по '|', убирает пробелы, создаёт объекты Rule.
     * "eps" в альтернативе означает пустую правую часть (ε-правило).
     */
    void parseRuleLine(const std::string& line);

    /*
     * computeFirstSets()
     * ------------------
     * Вычисляет FIRST(A) для каждого символа грамматики.
     *
     * FIRST(A) — множество терминалов, которые могут стоять первыми
     * в любой строке, выводимой из A (плюс "eps", если A ⇒* ε).
     *
     * Алгоритм (итерация до достижения неподвижной точки):
     *   1. FIRST(терминал) = {терминал}.
     *      FIRST(нетерминал) = {} (пополняется итерационно).
     *   2. Для каждого правила A → X1 X2 … Xn:
     *        Добавляем FIRST(X1 X2 … Xn) в FIRST(A).
     *   3. Повторяем шаг 2 до тех пор, пока хоть что-то изменяется.
     *
     * Вспомогательный метод firstOfSequence([X1, …, Xn]) — FIRST последовательности:
     *   - Добавляем FIRST(Xi) \ {eps} в результат.
     *   - Если eps ∉ FIRST(Xi) — останавливаемся.
     *   - Если все Xi могут давать eps — добавляем eps.
     */
    void computeFirstSets();

    // Возвращает FIRST(X1 X2 … Xn) для заданной последовательности символов
    std::set<std::string> firstOfSequence(const std::vector<std::string>& seq) const;

    /*
     * computeFollowSets()
     * -------------------
     * Вычисляет FOLLOW(A) для каждого нетерминала A.
     *
     * FOLLOW(A) — множество терминалов, которые могут стоять
     * НЕПОСРЕДСТВЕННО после A в какой-либо сентенциальной форме.
     *
     * Алгоритм (итерация до неподвижной точки):
     *   1. FOLLOW(S) = {$}, где S — стартовый символ.
     *   2. Для каждого правила A → α B β:
     *        Добавляем FIRST(β) \ {eps} в FOLLOW(B).
     *        Если eps ∈ FIRST(β), добавляем FOLLOW(A) в FOLLOW(B).
     *   3. Повторяем шаг 2 до стабилизации.
     */
    void computeFollowSets();

    /*
     * buildParseTable()
     * -----------------
     * Вычисляет направляющие множества T(A → α) и заполняет таблицу разбора.
     *
     * T(A → α) = FIRST(α) \ {eps}
     *          ∪ FOLLOW(A), если eps ∈ FIRST(α)
     *
     * Запись в таблице: table[A][t] = индекс правила, для каждого t ∈ T(A → α).
     *
     * Если два разных правила для одного нетерминала дают один и тот же терминал
     * в направляющем множестве — это КОНФЛИКТ, грамматика НЕ является LL(1).
     *
     * Возвращает true, если конфликтов нет (грамматика LL(1)).
     */
    bool buildParseTable();

    // -------------------------------------------------------------------------
    // Вспомогательные строковые функции
    // -------------------------------------------------------------------------
    static std::vector<std::string> splitBy(const std::string& s,
                                            const std::string& delim);
    static std::vector<std::string> splitByWhitespace(const std::string& s);
    static std::string              trim(const std::string& s);
};
