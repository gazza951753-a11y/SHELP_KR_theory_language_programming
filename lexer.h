/**
 * lexer.h — лексический анализатор (токенизатор).
 *
 * Разбивает строку исходного кода на последовательность токенов.
 *
 * Поддерживаемые токены:
 *   TK_ID      — идентификатор: [a-zA-Z][a-zA-Z0-9]*
 *   TK_NUMBER  — числовая константа: целая, вещественная, научная нотация
 *                (напр.: 42, 3.14, 1e+18, 8.41E-10)
 *   TK_PLUS    — оператор '+'
 *   TK_STAR    — оператор '*'
 *   TK_ASSIGN  — знак присваивания '='
 *   TK_LPAREN  — левая скобка '('
 *   TK_RPAREN  — правая скобка ')'
 *   TK_EOF     — конец ввода
 *
 * При ошибке выбрасывается исключение LexerError с указанием строки/столбца.
 */

#pragma once

#include <stdexcept>
#include <string>

// =============================================================================
// Типы токенов
// =============================================================================
enum class TokenType {
    TK_ID,      ///< идентификатор (имя переменной)
    TK_NUMBER,  ///< числовая константа (целая/вещественная/научная)
    TK_PLUS,    ///< '+'
    TK_STAR,    ///< '*'
    TK_ASSIGN,  ///< '='
    TK_LPAREN,  ///< '('
    TK_RPAREN,  ///< ')'
    TK_EOF      ///< конец ввода
};

/// Возвращает удобочитаемое название типа токена (для сообщений об ошибках)
std::string tokenTypeName(TokenType t);

// =============================================================================
// Одиночный токен
// =============================================================================
struct Token {
    TokenType   type;   ///< Тип токена
    std::string value;  ///< Исходный текст токена
    int         line;   ///< Строка в источнике (нумерация с 1)
    int         col;    ///< Столбец в источнике (нумерация с 1)

    Token(TokenType type, std::string value, int line, int col)
        : type(type), value(std::move(value)), line(line), col(col) {}
};

// =============================================================================
// Лексический анализатор
// =============================================================================
class Lexer {
public:
    /// Конструктор: принимает полный исходный текст для анализа
    explicit Lexer(const std::string& source);

    /// Вернуть следующий токен и продвинуть позицию
    Token nextToken();

    /// Подсмотреть следующий токен без продвижения позиции (lookahead = 1)
    Token peekToken();

private:
    std::string src_;      ///< Исходный текст
    size_t      pos_;      ///< Текущая позиция в src_
    int         line_;     ///< Текущая строка (нумерация с 1)
    int         col_;      ///< Текущий столбец (нумерация с 1)

    bool  hasPeeked_;      ///< Флаг: есть ли сохранённый peek-токен
    Token peeked_;         ///< Сохранённый peek-токен

    // --- внутренние вспомогательные методы ---

    /// Вернуть текущий символ (или '\0' при выходе за конец)
    char current() const;

    /// Вернуть текущий символ и продвинуть pos_, обновив line_/col_
    char advance();

    /// Пропустить пробельные символы (пробел, \t, \r, \n)
    void skipWhitespace();

    /// Считать числовой литерал начиная с текущей позиции
    Token readNumber(int startLine, int startCol);

    /// Считать идентификатор начиная с текущей позиции
    Token readIdent(int startLine, int startCol);

    /// Считать и вернуть следующий токен (без учёта пикинга)
    Token readToken();

    /// Проверить, достигнут ли конец источника
    bool atEnd() const;
};

// =============================================================================
// Исключение лексической ошибки
// =============================================================================
class LexerError : public std::runtime_error {
public:
    int line;  ///< Строка, где обнаружена ошибка
    int col;   ///< Столбец, где обнаружена ошибка

    LexerError(const std::string& msg, int line, int col)
        : std::runtime_error(msg), line(line), col(col) {}
};
