/*
 * lexer.h — заголовочный файл лексического анализатора (лексера/токенизатора).
 *
 * Лексический анализ — первый этап компиляции. Задача лексера: прочитать
 * исходный текст символ за символом и разбить его на токены (лексемы).
 * Каждый токен — это минимальная смысловая единица языка.
 *
 * В нашей задаче анализируются объявления структур вида:
 *   struct Point { int x; double y; };
 *
 * Типы токенов (TokenType):
 *   ┌─────────────────┬─────────────────────────────────────────────────────┐
 *   │ Тип токена      │ Что означает                                        │
 *   ├─────────────────┼─────────────────────────────────────────────────────┤
 *   │ KW_STRUCT       │ ключевое слово "struct"                             │
 *   │ KW_INT          │ ключевое слово "int"                                │
 *   │ KW_DOUBLE       │ ключевое слово "double"                             │
 *   │ KW_FLOAT        │ ключевое слово "float"                              │
 *   │ KW_CHAR         │ ключевое слово "char"                               │
 *   │ KW_BOOL         │ ключевое слово "bool"                               │
 *   │ KW_STRING       │ ключевое слово "string"                             │
 *   │ IDENTIFIER      │ идентификатор: [A-Za-z_][A-Za-z0-9_]*              │
 *   │                 │  → в грамматике это терминал <identifier>          │
 *   │ INTEGER         │ целое число: [0-9]+                                 │
 *   │                 │  → в грамматике это терминал <integer>             │
 *   │ LBRACE          │ '{'                                                 │
 *   │ RBRACE          │ '}'                                                 │
 *   │ SEMICOLON       │ ';'                                                 │
 *   │ LBRACKET        │ '['                                                 │
 *   │ RBRACKET        │ ']'                                                 │
 *   │ EOF_TOKEN       │ конец входного потока (маркер $)                   │
 *   └─────────────────┴─────────────────────────────────────────────────────┘
 *
 * Метод grammarSymbol() переводит тип токена в строку-терминал грамматики,
 * например: KW_INT → "int", IDENTIFIER → "<identifier>", EOF_TOKEN → "$".
 * Это нужно для связи лексера с парсером.
 */

#pragma once

#include <stdexcept>
#include <string>
#include <vector>

// =============================================================================
// Перечисление типов токенов
// =============================================================================
enum class TokenType {
    // Ключевые слова языка
    KW_STRUCT,
    KW_INT,
    KW_DOUBLE,
    KW_FLOAT,
    KW_CHAR,
    KW_BOOL,
    KW_STRING,

    // Токены, для которых важен конкретный текст
    IDENTIFIER,   // терминал грамматики: <identifier>
    INTEGER,      // терминал грамматики: <integer>

    // Одиночные символы-разделители
    LBRACE,       // {
    RBRACE,       // }
    SEMICOLON,    // ;
    LBRACKET,     // [
    RBRACKET,     // ]

    // Маркер конца потока
    EOF_TOKEN     // терминал грамматики: $
};

// =============================================================================
// Структура Token — одна лексема с информацией о позиции в тексте
// =============================================================================
struct Token {
    TokenType   type;   // тип токена (что это за лексема)
    std::string value;  // исходный текст лексемы, например "Point", "42", "{"
    int         line;   // номер строки (считается с 1)
    int         col;    // номер столбца — позиция начала лексемы (с 1)

    Token(TokenType t, std::string v, int l, int c)
        : type(t), value(std::move(v)), line(l), col(c) {}

    /*
     * grammarSymbol() — возвращает строку-терминал для таблицы разбора.
     *
     * Примеры:
     *   KW_INT      → "int"
     *   IDENTIFIER  → "<identifier>"
     *   LBRACE      → "{"
     *   EOF_TOKEN   → "$"
     *
     * Это связующее звено между лексером и грамматикой/парсером.
     */
    std::string grammarSymbol() const;

    // Читаемое название типа для сообщений об ошибках
    std::string typeName() const;
};

// =============================================================================
// LexerError — исключение при обнаружении недопустимого символа
// =============================================================================
class LexerError : public std::runtime_error {
public:
    int line, col;  // позиция ошибки в исходном тексте
    LexerError(const std::string& msg, int l, int c)
        : std::runtime_error(msg), line(l), col(c) {}
};

// =============================================================================
// Lexer — основной класс лексического анализатора
// =============================================================================
class Lexer {
public:
    /*
     * Конструктор.
     * @param source  Полный текст исходного файла (может быть многострочным).
     */
    explicit Lexer(const std::string& source);

    /*
     * tokenize() — разбивает весь исходный текст на токены.
     * Последний токен в векторе всегда EOF_TOKEN.
     * Генерирует LexerError при встрече неизвестного символа.
     */
    std::vector<Token> tokenize();

private:
    std::string src_;   // исходный текст программы
    size_t      pos_;   // текущая позиция (индекс символа) в src_
    int         line_;  // текущая строка (с 1)
    int         col_;   // текущий столбец (с 1)

    // Возвращает текущий символ (или '\0' если достигнут конец)
    char cur() const;

    // Смотрит вперёд на offset символов, не сдвигая позицию
    char peek(size_t offset = 1) const;

    // Считывает текущий символ, обновляет счётчики строки/столбца
    char advance();

    // Пропускает пробелы и однострочные комментарии (//)
    void skipWhitespace();

    // Считывает идентификатор или ключевое слово начиная с текущей позиции
    Token readIdentifierOrKeyword();

    // Считывает целочисленный литерал начиная с текущей позиции
    Token readInteger();

    // Возвращает true если pos_ >= src_.size() (конец строки)
    bool atEnd() const;
};
