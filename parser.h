/**
 * parser.h — рекурсивный нисходящий парсер (ДМПА / DPDA).
 *
 * Реализует нисходящий разбор без возвратов (LL(1)) для грамматики:
 *
 *   ASSIGN  -> ID '=' EXPR
 *   EXPR    -> TERM EXPR'
 *   EXPR'   -> '+' TERM EXPR'  |  ε
 *   TERM    -> FACTOR TERM'
 *   TERM'   -> '*' FACTOR TERM'  |  ε
 *   FACTOR  -> '(' EXPR ')'  |  NUMBER  |  ID
 *
 * Каждое нетерминальное правило — отдельный приватный метод parseXxx().
 * Парсер потребляет токены из Lexer и строит АСД (AST).
 *
 * Эквивалентность ДМПА:
 *   Стек ДМПА моделируется стеком вызовов рекурсивных функций.
 *   Каждая функция parseXxx соответствует одному состоянию автомата.
 *   Переходы управляются текущим токеном (lookahead = 1 токен).
 */

#pragma once

#include "ast.h"
#include "lexer.h"

#include <stdexcept>

// =============================================================================
// Исключение синтаксической ошибки
// =============================================================================
class ParseError : public std::runtime_error {
public:
    int line;  ///< Строка, где обнаружена ошибка
    int col;   ///< Столбец, где обнаружена ошибка

    ParseError(const std::string& msg, int line, int col)
        : std::runtime_error(msg), line(line), col(col) {}
};

// =============================================================================
// Рекурсивный нисходящий парсер
// =============================================================================
class Parser {
public:
    /// Принимает ссылку на готовый лексер
    explicit Parser(Lexer& lexer);

    /**
     * Разобрать весь ввод и вернуть корень АСД (AssignNode).
     * Выбрасывает ParseError при синтаксической ошибке.
     */
    ASTNodePtr parse();

private:
    Lexer& lexer_;  ///< Источник токенов

    // -------------------------------------------------------------------------
    // Методы, соответствующие правилам грамматики
    // -------------------------------------------------------------------------

    /// ASSIGN -> ID '=' EXPR
    ASTNodePtr parseAssign();

    /// EXPR -> TERM EXPR'
    ASTNodePtr parseExpr();

    /// EXPR' -> '+' TERM EXPR' | ε
    /// Принимает уже разобранный левый операнд (left-folding)
    ASTNodePtr parseExprPrime(ASTNodePtr left);

    /// TERM -> FACTOR TERM'
    ASTNodePtr parseTerm();

    /// TERM' -> '*' FACTOR TERM' | ε
    /// Принимает уже разобранный левый операнд (left-folding)
    ASTNodePtr parseTermPrime(ASTNodePtr left);

    /// FACTOR -> '(' EXPR ')' | NUMBER | ID
    ASTNodePtr parseFactor();

    // -------------------------------------------------------------------------
    // Вспомогательные методы
    // -------------------------------------------------------------------------

    /**
     * Потребовать токен заданного типа.
     * Если текущий токен не совпадает — выбросить ParseError.
     * При успехе возвращает потреблённый токен.
     */
    Token expect(TokenType type);
};
